"""阶段生成器与 Pipeline 标准状态之间的适配层。

本模块负责：
- 将全局 config + 上一阶段结果转换为某阶段 generate_* 所需的局部配置；
- 将真实阶段生成器输出标准化为 pipeline 使用的 stage_X_result；
- 显式处理 MA/kA、Vs/Wb 字段差异；
- 提供 Stage 2 → Stage 3 的真实生成器适配。
"""

from __future__ import annotations

from typing import Any

COIL_NAMES = ("CS1", "CS2", "CS3", "PF1", "PF2", "PF3", "PF4", "Div1", "Div2", "VS")


def ma_to_ka(value_ma: float) -> float:
    """MA 转 kA。"""

    return float(value_ma) * 1000.0


def ka_to_ma(value_ka: float) -> float:
    """kA 转 MA。"""

    return float(value_ka) / 1000.0


def coil_state_ma_to_ka(coil_state_ma: dict[str, Any]) -> dict[str, float]:
    """线圈状态 MA → kA。"""

    return {name: ma_to_ka(float(coil_state_ma.get(name, 0.0))) for name in COIL_NAMES}


def coil_state_ka_to_ma(coil_state_ka: dict[str, Any]) -> dict[str, float]:
    """线圈状态 kA → MA。"""

    return {name: ka_to_ma(float(coil_state_ka.get(name, 0.0))) for name in COIL_NAMES}


