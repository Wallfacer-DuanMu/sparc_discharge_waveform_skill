def normalize_stage_2_result_for_pipeline(raw_result: dict[str, Any], config: dict[str, Any], stage_1_result: dict[str, Any]) -> dict[str, Any]:
    """将 Stage 2 真实生成器输出标准化为 pipeline 的 stage_2_result。"""

    summary = raw_result.get("summary", {})
    validation = raw_result.get("rampup_validation", {})
    handoff = raw_result.get("handoff_to_stage_3", {})
    coil_state_ma = coil_state_ka_to_ma(raw_result.get("coil_state_at_rampup_end", {}))
    shape_state = _normalize_stage_2_shape_state(raw_result.get("shape_state_at_rampup_end", {}), config)

    return {
        "stage_name": "rampup",
        "execution_mode": "stage_generator",
        "time_range_s": {
            "start": float(summary.get("start_time_s", config["timeline"]["breakdown_end_s"])),
            "end": float(summary.get("end_time_s", config["timeline"]["rampup_end_s"])),
        },
        "Ip_at_rampup_start_MA": float(summary.get("start_plasma_current_MA", stage_1_result["Ip_at_breakdown_end_MA"])),
        "Ip_at_rampup_end_MA": float(summary.get("end_plasma_current_MA", config["target"]["Ip_flat_MA"])),
        "coil_state_at_rampup_start": stage_1_result.get("coil_state_at_breakdown_end", {}),
        "coil_state_at_rampup_end": coil_state_ma,
        "shape_state_at_rampup_end": shape_state,
        "cs_flux_used_rampup_Vs": round(float(summary.get("stage_2_flux_consumed_Wb", 0.0)), 6),
        "cs_flux_remaining_after_rampup_Vs": round(float(handoff.get("flux_remaining_Wb", raw_result.get("cs_flux_remaining_after_rampup_Wb", 0.0))), 6),
        "physics_diagnostics": raw_result.get("physics_diagnostics", {}),
        "handoff_to_stage_3": handoff,
        "raw_stage_result_summary": summary,
        "waveform_rows": raw_result.get("rampup_waveform", []),
        "waveform_ref": f"outputs/{config.get('case_name', 'unnamed_case')}/stage_2_rampup_waveform.csv",
        "rampup_validation": validation,
    }


